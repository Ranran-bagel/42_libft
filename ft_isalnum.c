int	ft_isalnum(int c)
{
	unsigned char	uc;

	uc = (unsigned char)c;
	if ((uc <= '9' && uc >= '0') || (uc <= 'z' && uc >= 'a')
		|| (uc <= 'Z' && uc >= 'A'))
		return (1);
	return (0);
}
